// Walking characters. Slots: 1 outline, hair, and eyes (usually black), 2 clothes and the crest, 3 skin.
// Templates keep that order so the lead can recolor them per person. Faces are framed in slot 1 so
// skin never touches the ground tile directly.
import { C } from '../../engine/palette';
import type { CharArt, Rows } from './types';

/** The second walk frame: the same rows with the bottom rows replaced. */
function step(rows: Rows, ...tail: string[]): Rows {
  return [...rows.slice(0, rows.length - tail.length), ...tail];
}

/** A character whose second frame in each facing differs only in its bottom rows. */
function walker(pal: CharArt['pal'], d: Rows, dt: string[], u: Rows, ut: string[], s: Rows, st: string[]): CharArt {
  return { pal, down: [d, step(d, ...dt)], up: [u, step(u, ...ut)], side: [s, step(s, ...st)] };
}

