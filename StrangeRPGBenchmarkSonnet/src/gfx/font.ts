export const FONT_W = 3;
export const FONT_H = 5;
export const ADV = 4;

export function glyph(ch: string): string {
  const c = ch.toUpperCase();
  return G[c] ?? G['?'];
}

export function textWidth(s: string): number {
  return s.length * ADV - 1;
}

/** Word-wraps text into lines no wider than `cols` characters. Newlines are kept. */
export function wrap(text: string, cols: number): string[] {
  const out: string[] = [];
  for (const para of text.split('\n')) {
    let line = '';
    for (const w of para.split(' ')) {
      if (!line.length) line = w;
      else if (line.length + 1 + w.length <= cols) line += ' ' + w;
      else { out.push(line); line = w; }
      while (line.length > cols) { out.push(line.slice(0, cols)); line = line.slice(cols); }
    }
    out.push(line);
  }
  return out;
}
