const pct = (x: number, d = 0) => `${(x * 100).toFixed(d)}%`;
const f1 = (x: number) => x.toFixed(1);
const mean = (a: number[]) => (a.length ? a.reduce((x, y) => x + y, 0) / a.length : 0);
const clamp01 = (x: number) => Math.max(0, Math.min(1, x));
const band = (x: number, lo: number, hi: number, soft: number) => clamp01(1 - Math.max(0, lo - x, x - hi) / soft);

function setLevelOffset(s: GameState, off: number) {
  for (const m of s.roster) { m.lvl = Math.max(1, m.lvl + off); const st = memberStats(m); m.hp = st.hp; m.mp = st.mp; }
}

interface Agg { win: number; hpLeft: number; rounds: number; close: number; low: number; n: number; mpFrac: number; items: number; ko: number }
function agg(rs: FightRecord[]): Agg {
  const wins = rs.filter((r) => r.win);
  return {
    n: rs.length, win: rs.filter((r) => r.win).length / rs.length, hpLeft: mean(rs.map((r) => r.hpLeft)), rounds: mean(rs.map((r) => r.rounds)),
    close: wins.length ? wins.filter((r) => r.minHp < 0.4).length / wins.length : 0, low: wins.length ? wins.filter((r) => r.low).length / wins.length : 0,
    mpFrac: mean(rs.map((r) => r.mpFrac)), items: mean(rs.map((r) => r.items)), ko: mean(rs.map((r) => r.ko)),
  };
}

function bossFight(ch: number, p: Policy, rng: Rng, off = 0, ids?: string[]): FightRecord {
  const s = chapterState(ch, ids, BOSS_BONUS);
  if (off) setLevelOffset(s, off);
  let last!: FightRecord;
  for (const g of BOSSES[ch]) last = fight(s, g, true, p, rng, 0.85, { noApply: true });
  return last;
}
function regFight(ch: number, p: Policy, rng: Rng, off = 0): FightRecord {
  const s = chapterState(ch, undefined, REG_BONUS);
  if (off) setLevelOffset(s, off);
  return fight(s, pickEncounter(ch, rng), false, p, rng, 0.5, { noApply: true });
}

