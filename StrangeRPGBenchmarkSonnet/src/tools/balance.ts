for (let ch = 1; ch <= 12; ch++) {
  const rng = new Rng(ch * 31 + 5);
  const cells = offs.map((o) => { let w = 0; const n = Math.max(20, Math.floor(N / 2)); for (let i = 0; i < n; i++) w += bossFight(ch, 'smart', rng, o).win ? 1 : 0; return w / n; });
  slopeByCh.push(cells[offs.indexOf(0)] - cells[0]);
  log(`| ${ch} | ${cells.map((c) => pct(c)).join(' | ')} |`);
}

