// ---------------------------------------------------------------- 4. party viability
log();
log('## 4. Party composition viability');
log();
log('Boss win rate of the smart bot for sampled four-member parties that always include Wick. The tenth percentile shows how a poorly matched party fares. A small gap between it and the median means every partymate can carry a slot.');
log();
log('| Ch | Roster | Parties | Best | 10th percentile | Median | Mean | Worst | P10 / median |');
log('|---|---|---|---|---|---|---|---|---|');
const chapterMeans: number[] = [];
const viability: number[] = [];
for (let ch = 3; ch <= 12; ch++) {
  const rng = new Rng(ch * 71);
  const roster = CHARS.filter((c) => c.joinChapter <= ch).map((c) => c.id);
  const combos: string[][] = [];
  const COMBOS = 24;
  for (let i = 0; i < COMBOS; i++) {
    const pool = roster.filter((id) => id !== 'wick');
    const pick = ['wick'];
    while (pick.length < 4 && pool.length) pick.push(pool.splice(rng.int(pool.length), 1)[0]);
    combos.push(pick);
  }
  const n = Math.max(12, Math.floor(N / 4));
  const rates = combos.map((ids) => { let w = 0; for (let i = 0; i < n; i++) w += bossFight(ch, 'smart', rng, 0, ids).win ? 1 : 0; return w / n; }).sort((a, b) => a - b);
  const p10 = rates[Math.floor(rates.length * 0.1)], med = rates[Math.floor(rates.length / 2)];
  viability.push(med > 0 ? p10 / med : 0);
  chapterMeans.push(mean(rates));
  log(`| ${ch} | ${roster.length} | ${combos.length} | ${pct(rates[rates.length - 1])} | ${pct(p10)} | ${pct(med)} | ${pct(mean(rates))} | ${pct(rates[0])} | ${med > 0 ? (p10 / med).toFixed(2) : '-'} |`);
}

// ---------------------------------------------------------------- 5. character contribution
log();
log('## 5. Contribution per partymate');
log();
log('Each character is tested in boss fights at chapter 12 in a party of Wick, that character, and two random partymates. The table shows the character\'s share of party damage and healing and how the smart bot used the character\'s six skills.');
log();
log('| Character | Class | Fights | Damage share | Healing share | Skills used | Top skill share | Most used skill |');
log('|---|---|---|---|---|---|---|---|');
const covers: Record<string, number> = {};
let maxDominance = 0;
for (const c of CHARS) {
  const rng = new Rng(hashStr(c.id));
  const dmg: number[] = [], heal: number[] = [];
  const use: Record<string, number> = {};
  const fights = Math.max(16, Math.floor(N / 3));
  for (let i = 0; i < fights; i++) {
    const pool = CHARS.filter((x) => x.id !== 'wick' && x.id !== c.id).map((x) => x.id);
    const ids = ['wick', ...(c.id === 'wick' ? [] : [c.id])];
    while (ids.length < 4) ids.push(pool.splice(rng.int(pool.length), 1)[0]);
    const r = bossFight(12, 'smart', rng, 0, ids);
    const td = Object.values(r.dmgByChar).reduce((a, b) => a + b, 0) || 1;
    const th = Object.values(r.healByChar).reduce((a, b) => a + b, 0) || 1;
    dmg.push(r.dmgByChar[c.id] / td);
    heal.push(r.healByChar[c.id] / th);
    for (const [k, v] of Object.entries(r.actions)) if (c.learn.some(([, s]) => s === k)) use[k] = (use[k] ?? 0) + v;
  }
  const total = Object.values(use).reduce((a, b) => a + b, 0) || 1;
  const topSkill = Object.entries(use).sort((a, b) => b[1] - a[1])[0];
  const top = topSkill ? topSkill[1] / total : 0;
  const cover = c.learn.filter(([, s]) => (use[s] ?? 0) > 0).length / c.learn.length;
  covers[c.id] = cover;
  maxDominance = Math.max(maxDominance, top);
  log(`| ${c.name} | ${c.cls} | ${fights} | ${pct(mean(dmg))} | ${pct(mean(heal))} | ${Math.round(cover * 6)}/6 | ${pct(top)} | ${topSkill ? SKILLS[topSkill[0]].name : '-'} |`);
}

