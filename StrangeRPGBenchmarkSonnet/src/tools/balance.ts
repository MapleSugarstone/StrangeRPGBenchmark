log('|---|---|---|---|---|---|---|---|---|---|---|---|---|');
const rows: Record<number, { sReg: Agg; sBoss: Agg; mReg: Agg; mBoss: Agg; rReg: Agg; rBoss: Agg; cReg: Agg; cBoss: Agg }> = {};
const smartRecs: FightRecord[][] = [];
for (let ch = 1; ch <= 12; ch++) {
  const rng = new Rng(ch * 1009);
  const col: Record<string, FightRecord[]> = { sReg: [], sBoss: [], mReg: [], mBoss: [], rReg: [], rBoss: [], cReg: [], cBoss: [] };
  for (let i = 0; i < N; i++) {
    col.sReg.push(regFight(ch, 'smart', rng)); col.sBoss.push(bossFight(ch, 'smart', rng));
    col.mReg.push(regFight(ch, 'mash', rng)); col.mBoss.push(bossFight(ch, 'mash', rng));
    col.cReg.push(regFight(ch, 'casual', rng)); col.cBoss.push(bossFight(ch, 'casual', rng));
    if (i < N / 2) { col.rReg.push(regFight(ch, 'random', rng)); col.rBoss.push(bossFight(ch, 'random', rng)); }
  }
  rows[ch] = { sReg: agg(col.sReg), sBoss: agg(col.sBoss), mReg: agg(col.mReg), mBoss: agg(col.mBoss), rReg: agg(col.rReg), rBoss: agg(col.rBoss), cReg: agg(col.cReg), cBoss: agg(col.cBoss) };
  smartRecs.push([...col.sReg, ...col.sBoss]);
  const r = rows[ch];
  log(`| ${ch} | ${pct(r.sReg.win)} | ${pct(r.sBoss.win)} | ${pct(r.cReg.win)} | ${pct(r.cBoss.win)} | ${pct(r.mReg.win)} | ${pct(r.mBoss.win)} | ${pct(r.rReg.win)} | ${pct(r.rBoss.win)} | ${f1(r.sReg.rounds)} | ${f1(r.sBoss.rounds)} | ${pct(r.sReg.hpLeft)} | ${pct(r.sBoss.hpLeft)} |`);
}

