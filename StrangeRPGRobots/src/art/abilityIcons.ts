const cache = new Map<string, Img>();
export function abilityIcon(name: string, dim = false): Img {
  const key = name + (dim ? ':d' : '');
  const hit = cache.get(key);
  if (hit) return hit;
  const pat = P[name] ?? P.item;
  const rows: string[] = [];
  rows.push('0000000000');
  for (let y = 0; y < 8; y++) rows.push('0' + (pat[y] ?? '........').slice(0, 8).padEnd(8, '.').replace(/\./g, '2') + '0');
  rows.push('0000000000');
  const bg = dim ? C.ink : CAT[name] ?? C.amb1;
  const fg = dim ? C.slate : C.white;
  const im = img(rows, [fg, bg]);
  cache.set(key, im);
  return im;
}
