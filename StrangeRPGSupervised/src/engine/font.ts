/**
 * Draw text at the given position with the given color.
 */
export function drawText(
  buffer: ImageData,
  text: string,
  x: number,
  y: number,
  color: string
): void {
  // The UI audit collects every text box drawn while this list exists.
  const boxes = (globalThis as any).__textBoxes;
  if (boxes) boxes.push({ text, x, y, w: textWidth(text), h: 8 });
  const rgba = hexToRgba(color);
  let cx = x;
  for (const ch of text) {
    const glyph = GLYPHS[ch];
    if (!glyph) continue;
    for (let row = 0; row < 8; row++) {
      const line = glyph[row];
      for (let col = 0; col < 5; col++) {
        if (line[col] === "#") {
          const idx = (y + row) * 192 * 4 + (cx + col) * 4;
          buffer.data[idx] = rgba[0];
          buffer.data[idx + 1] = rgba[1];
          buffer.data[idx + 2] = rgba[2];
          buffer.data[idx + 3] = rgba[3];
        }
      }
    }
    cx += 6; // 5 pixels + 1 pixel gap
  }
}

/**
 * Draw a scaled glyph from the font data directly into the buffer.
 * Used for large title text to avoid canvas context overhead and ensure pixel-perfect scaling.
 */
export function drawScaledGlyph(
  buffer: ImageData,
  glyph: string[],
  x: number,
  y: number,
  scale: number,
  color: string
): void {
  const rgba = hexToRgba(color);
  for (let row = 0; row < 8; row++) {
    const line = glyph[row];
    for (let col = 0; col < 5; col++) {
      if (line[col] === "#") {
        const srcX = x + col * scale;
        const srcY = y + row * scale;
        for (let dy = 0; dy < scale; dy++) {
          for (let dx = 0; dx < scale; dx++) {
            const idx = (srcY + dy) * 192 * 4 + (srcX + dx) * 4;
            buffer.data[idx] = rgba[0];
            buffer.data[idx + 1] = rgba[1];
            buffer.data[idx + 2] = rgba[2];
            buffer.data[idx + 3] = rgba[3];
          }
        }
      }
    }
  }
}

function hexToRgba(hex: string): [number, number, number, number] {
  const r = parseInt(hex.slice(1, 3), 16);
  const g = parseInt(hex.slice(3, 5), 16);
  const b = parseInt(hex.slice(5, 7), 16);
  return [r, g, b, 255];
}

/**
 * Calculate the width of text in pixels.
 */
export function textWidth(text: string): number {
  return text.length * 6;
}
