/**
 * Move kinds for Ruin moves.
 */
export enum MoveKind {
  Dash = 'Dash',
  Projectile = 'Projectile',
  Spell = 'Spell',
  Channel = 'Channel',
}

/**
 * Reach types for Ruin moves.
 */
export enum Reach {
  Single = 'Single',
  Spread = 'Spread',
  Ally = 'Ally',
  WholeTeam = 'WholeTeam',
}

/**
 * Attack types for Ruin moves.
 */
export enum AttackKind {
  Physical = 'Physical',
  Magic = 'Magic',
}

/**
 * Data model for a Ruin move.
 */
export interface MoveData {
  name: string;
  type: string; // Type enum key
  power: number; // Base power ratio (e.g., 1.0 for 100%)
  kind: MoveKind;
  reach: Reach;
  cooldown: number; // Turns before reuse
  boostCost: number; // Boost spent to use
  windup: number; // Turns to wind up (0 = instant)
  status?: string; // Status name
  statusChance?: number; // Chance to apply status (0-100)
  description: string;
}

/**
 * A move instance in battle, including cooldown state.
 */
export interface MoveInstance {
  data: MoveData;
  cooldownLeft: number;
}

