// Bundles the TypeScript music sources in audio/ into src/music.js, a classic script that defines the global Music.
// Usage: node tools/build-music.mjs
// Uses an esbuild that is already on this machine. Set ESBUILD_PATH to point at another copy.
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);

const CANDIDATES = [
  process.env.ESBUILD_PATH,
  'esbuild',
  path.join(root, '..', 'node_modules', 'esbuild'),
  'C:/Users/Krazv/Documents/ElipsusVenum/node_modules/esbuild',
  path.join(root, '..', 'StrangeRPGBenchmarkClaude', 'node_modules', 'esbuild'),
  path.join(root, '..', 'WeirdJRPG', 'node_modules', 'esbuild'),
].filter(Boolean);

function findEsbuild() {
  for (const c of CANDIDATES) {
    try { return require(c); } catch { /* try the next one */ }
  }
  console.error('No esbuild found. Tried:\n  ' + CANDIDATES.join('\n  '));
  process.exit(1);
}

const esbuild = findEsbuild();
await esbuild.build({
  entryPoints: [path.join(root, 'audio', 'main.ts')],
  outfile: path.join(root, 'src', 'music.js'),
  bundle: true,
  format: 'iife',
  target: 'es2022',
  charset: 'utf8',
  legalComments: 'none',
  banner: { js: '// Generated by tools/build-music.mjs from the sources in audio/. Edit those and rebuild.' },
  logLevel: 'warning',
});
console.log(`src/music.js built with esbuild ${esbuild.version}`);
