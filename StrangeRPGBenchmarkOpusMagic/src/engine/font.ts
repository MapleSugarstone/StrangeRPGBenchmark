interface Glyph { w: number; bits: [number, number][] }
const glyphs = new Map<string, Glyph>();
for (const [ch, rows] of Object.entries(G)) {
  const bits: [number, number][] = [];
  let w = 4;
  rows.forEach((r, y) => {
    w = Math.max(w, r.length);
    for (let x = 0; x < r.length; x++) if (r[x] === '#') bits.push([x, y]);
  });
  glyphs.set(ch, { w, bits });
}

export function glyphBits(ch: string): [number, number][] {
  return (glyphs.get(ch) ?? glyphs.get('?')!).bits;
}

export function glyph(ch: string, x: number, y: number, rgb: number) {
  x = Math.round(x);
  y = Math.round(y);
  const g = glyphs.get(ch) ?? glyphs.get('?')!;
  const p = px(rgb);
  for (const [gx, gy] of g.bits) {
    const xx = x + gx, yy = y + gy;
    if (xx >= 0 && yy >= 0 && xx < W && yy < H) buf[yy * W + xx] = p;
  }
}

export function text(s: string, x: number, y: number, rgb: number) {
  for (let i = 0; i < s.length; i++) glyph(s[i], x + i * CW, y, rgb);
}

/** Text with a one pixel dark outline, for drawing over the map. */
export function textShadow(s: string, x: number, y: number, rgb: number, shadow = 0x000000) {
  for (const [dx, dy] of [[1, 0], [-1, 0], [0, 1], [0, -1]]) text(s, x + dx, y + dy, shadow);
  text(s, x, y, rgb);
}

export function textCenter(s: string, cx: number, y: number, rgb: number) {
  text(s, Math.round(cx - (s.length * CW) / 2), y, rgb);
}

/** Splits text into lines of at most `cols` characters, breaking at spaces. */
export function wrap(s: string, cols: number): string[] {
  const out: string[] = [];
  for (const para of s.split('\n')) {
    let line = '';
    for (const word of para.split(' ')) {
      if (!line.length) { line = word; continue; }
      if (line.length + 1 + word.length <= cols) line += ` ${word}`;
      else { out.push(line); line = word; }
      while (line.length > cols) { out.push(line.slice(0, cols)); line = line.slice(cols); }
    }
    out.push(line);
  }
  return out;
}
