/** Adds sprites of any size, drawn at one pixel per pixel. */
export function registerSprites(defs: Record<string, Def>) {
  for (const [k, v] of Object.entries(defs)) { S[k] = v; cache.delete(k); }
}

export type Look = 'plain' | 'copied' | 'blank' | 'halted' | 'dark' | 'gray';

export interface DrawOpts {
  flip?: boolean;
  frame?: number;
  look?: Look;
  pal?: Pal;
  /** Extra ink marks drawn on Wait's page, one per line Wait has written, up to 12. */
  marks?: number;
  /** Only every other pixel, for ghosts and blinking. */
  dither?: number;
  /** Leaves the normal map alone, for flat things. */
  flat?: boolean;
  /** The sprite gives off its own light. */
  emissive?: boolean;
}

const WAIT_MARKS: [number, number, number][] = [
  [2, 2, 4], [3, 2, 5], [4, 2, 3], [4, 4, 5], [1, 2, 3], [5, 3, 5], [1, 4, 5], [3, 2, 2], [5, 2, 2], [2, 5, 5], [0, 3, 4], [4, 5, 5],
];
const WAIT16_MARKS: [number, number, number][] = [
  [4, 4, 9], [6, 4, 11], [8, 4, 7], [8, 9, 11], [2, 5, 8], [10, 5, 10], [3, 9, 11], [6, 12, 12], [10, 4, 4], [4, 11, 11], [1, 6, 9], [8, 12, 12],
];

export function lookPal(look: Look | undefined, pal: Pal): Pal {
  switch (look) {
    case 'copied': return [0x000000, LIME, LIME];
    case 'blank': return [0xd8d4cc, 0xd8d4cc, 0xd8d4cc];
    case 'halted': return [0x1a2030, 0x3a4458, 0x5a6478];
    case 'dark': return [0x000000, 0x000000, 0x000000];
    case 'gray': return [0x2a2a2a, 0x6a6a6a, 0x9a9a9a];
    default: return pal;
  }
}

export function drawSprite(key: string, x: number, y: number, o: DrawOpts = {}) {
  x = Math.round(x);
  y = Math.round(y);
  const d = get(key);
  const useAlt = !!(o.frame && d.alt);
  const idx = useAlt ? d.alt! : d.idx;
  const nm = useAlt ? d.nAlt! : d.n;
  const pal = lookPal(o.look, o.pal ?? d.pal);
  const P = [0, px(pal[0]), px(pal[1]), px(pal[2])];
  const w = d.w, h = d.h;
  let marks: Set<number> | null = null;
  if ((key === 'wait' || key === 'wait16') && o.marks) {
    marks = new Set();
    const table = key === 'wait' ? WAIT_MARKS : WAIT16_MARKS;
    for (let i = 0; i < Math.min(o.marks, table.length); i++) {
      const [ry, x0, x1] = table[i];
      for (let mx = x0; mx <= x1; mx++) marks.add(ry * w + mx);
    }
  }
  for (let sy = 0; sy < h; sy++) {
    const py = y + sy;
    if (py < 0 || py >= H) continue;
    for (let sx = 0; sx < w; sx++) {
      const pxx = x + sx;
      if (pxx < 0 || pxx >= W) continue;
      const srcX = o.flip ? w - 1 - sx : sx;
      const si = sy * w + srcX;
      let c = idx[si];
      if (!c) continue;
      if (o.dither !== undefined && ((pxx + py + o.dither) & 1)) continue;
      if (marks && marks.has(si) && c === 2) c = 3;
      const di = py * W + pxx;
      buf[di] = P[c];
      if (!o.flat) {
        nrm[di * 2] = o.flip ? -nm[si * 2] : nm[si * 2];
        nrm[di * 2 + 1] = nm[si * 2 + 1];
      }
      emi[di] = o.emissive ? 1 : 2;
    }
  }
}

/** Draws a creature in the copied style: a dithered double one step behind, then the lime body. */
export function drawCopied(key: string, x: number, y: number, o: DrawOpts, lag: number) {
  drawSprite(key, x - 1 - lag, y, { ...o, look: 'copied', dither: 0, emissive: true });
  drawSprite(key, x, y, { ...o, look: 'copied', emissive: true });
}

/** A small dithered shadow on the ground under something standing. */
export function dropShadow(x: number, y: number, w = 6) {
  const p = 0xff000000;
  for (let i = 0; i < w; i++) {
    const xx = Math.round(x + i), yy = Math.round(y);
    if (xx < 0 || xx >= W || yy < 0 || yy >= H) continue;
    if ((xx + yy) & 1) buf[yy * W + xx] = p;
    if (i > 0 && i < w - 1 && yy + 1 < H && !((xx + yy) & 1)) buf[(yy + 1) * W + xx] = p;
  }
}

