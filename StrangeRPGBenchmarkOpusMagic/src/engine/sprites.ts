interface Decoded { w: number; h: number; idx: Uint8Array; alt: Uint8Array | null; pal: Pal; n: Int8Array; nAlt: Int8Array | null }
const cache = new Map<string, Decoded>();

function decode(rows: string[], w: number, h: number): Uint8Array {
  const a = new Uint8Array(w * h);
  for (let y = 0; y < h; y++) {
    const r = rows[y] ?? '';
    for (let x = 0; x < w; x++) {
      const c = r[x];
      a[y * w + x] = c === '1' ? 1 : c === '2' ? 2 : c === '3' ? 3 : 0;
    }
  }
  return a;
}

/**
 * Builds a normal map from a sprite's shape: pixels deep inside face the viewer, pixels near the
 * silhouette lean outward, and darker palette slots sit a little lower.
 */
export function normalsOf(idx: Uint8Array, w: number, h: number, depth = 3): Int8Array {
  const dist = new Float32Array(w * h);
  for (let i = 0; i < w * h; i++) dist[i] = idx[i] ? depth : 0;
  for (let pass = 0; pass < depth; pass++) {
    for (let y = 0; y < h; y++) {
      for (let x = 0; x < w; x++) {
        const i = y * w + x;
        if (!idx[i]) continue;
        let m = depth;
        for (const [dx, dy] of [[1, 0], [-1, 0], [0, 1], [0, -1]]) {
          const xx = x + dx, yy = y + dy;
          const v = xx < 0 || yy < 0 || xx >= w || yy >= h ? 0 : dist[yy * w + xx];
          if (v + 1 < m) m = v + 1;
        }
        dist[i] = m;
      }
    }
  }
  const hgt = new Float32Array(w * h);
  for (let i = 0; i < w * h; i++) hgt[i] = idx[i] ? dist[i] + (idx[i] === 1 ? -0.6 : idx[i] === 3 ? 0.4 : 0) : 0;
  const n = new Int8Array(w * h * 2);
  const at = (x: number, y: number) => (x < 0 || y < 0 || x >= w || y >= h ? 0 : hgt[y * w + x]);
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      const i = y * w + x;
      if (!idx[i]) continue;
      let gx = (at(x - 1, y) - at(x + 1, y)) * 0.6;
      let gy = (at(x, y - 1) - at(x, y + 1)) * 0.6;
      const len = Math.sqrt(gx * gx + gy * gy + 1);
      gx /= len; gy /= len;
      n[i * 2] = Math.round(gx * 100);
      n[i * 2 + 1] = Math.round(gy * 100);
      if (n[i * 2] === 0 && n[i * 2 + 1] === 0) n[i * 2 + 1] = -1;
    }
  }
  return n;
}

function get(key: string): Decoded {
  let d = cache.get(key);
  if (d) return d;
  const def = S[key] ?? S.page;
  const w = def.w ?? 8, h = def.h ?? 8;
  const idx = decode(def.rows, w, h);
  const alt = def.alt ? decode(def.alt, w, h) : null;
  d = { w, h, idx, alt, pal: def.pal, n: normalsOf(idx, w, h), nAlt: alt ? normalsOf(alt, w, h) : null };
  cache.set(key, d);
  return d;
}

export function hasSprite(key: string) { return key in S; }
export function allSpriteDefs(): Record<string, Def> { return S; }
export function spritePal(key: string): Pal { return get(key).pal; }
