const tileNormals = new WeakMap<string[], Int8Array>();

/** A tile's relief: brighter palette slots stand higher than darker ones. */
function tileNormalsOf(rows: string[]): Int8Array {
  let n = tileNormals.get(rows);
  if (n) return n;
  const hgt = (x: number, y: number) => {
    const c = rows[(y + 8) % 8].charCodeAt((x + 8) % 8) - 48;
    return c >= 1 && c <= 3 ? c : 0;
  };
  n = new Int8Array(128);
  for (let y = 0; y < 8; y++) {
    for (let x = 0; x < 8; x++) {
      let gx = (hgt(x - 1, y) - hgt(x + 1, y)) * 0.35;
      let gy = (hgt(x, y - 1) - hgt(x, y + 1)) * 0.35;
      const len = Math.sqrt(gx * gx + gy * gy + 1);
      gx /= len; gy /= len;
      n[(y * 8 + x) * 2] = Math.round(gx * 100);
      n[(y * 8 + x) * 2 + 1] = Math.round(gy * 100);
    }
  }
  tileNormals.set(rows, n);
  return n;
}

export function drawTile(t: TileDef, x: number, y: number, pal: Pal, frame: number) {
  x = Math.round(x);
  y = Math.round(y);
  const rows = frame && t.alt ? t.alt : t.rows;
  const P = [0, px(pal[0]), px(pal[1]), px(pal[2])];
  const nm = tileNormalsOf(rows);
  const g = t.glow ?? 0;
  for (let sy = 0; sy < 8; sy++) {
    const py = y + sy;
    if (py < 0 || py >= H) continue;
    const r = rows[sy];
    for (let sx = 0; sx < 8; sx++) {
      const c = r.charCodeAt(sx) - 48;
      const pxx = x + sx;
      if (pxx < 0 || pxx >= W) continue;
      if (c < 1 || c > 3) continue;
      const di = py * W + pxx;
      buf[di] = P[c];
      const si = (sy * 8 + sx) * 2;
      nrm[di * 2] = nm[si];
      nrm[di * 2 + 1] = nm[si + 1];
      emi[di] = g && c >= g ? 1 : 0;
    }
  }
}

