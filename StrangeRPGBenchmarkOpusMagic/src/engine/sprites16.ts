// ---------------------------------------------------------------- generated larger sprites

export class Canvas {
  g: number[][];
  constructor(public w: number, public h: number) { this.g = Array.from({ length: h }, () => new Array(w).fill(0)); }
  set(x: number, y: number, c: number) { x = Math.round(x); y = Math.round(y); if (x >= 0 && y >= 0 && x < this.w && y < this.h) this.g[y][x] = c; }
  get(x: number, y: number) { return x >= 0 && y >= 0 && x < this.w && y < this.h ? this.g[y][x] : 0; }
  disc(cx: number, cy: number, r: number, c: number) {
    for (let y = 0; y < this.h; y++) for (let x = 0; x < this.w; x++) if ((x - cx) ** 2 + (y - cy) ** 2 <= r * r) this.g[y][x] = c;
  }
  ring(cx: number, cy: number, r: number, t: number, c: number) {
    for (let y = 0; y < this.h; y++) for (let x = 0; x < this.w; x++) {
      const d = Math.sqrt((x - cx) ** 2 + (y - cy) ** 2);
      if (d <= r && d > r - t) this.g[y][x] = c;
    }
  }
  line(x0: number, y0: number, x1: number, y1: number, c: number) {
    const n = Math.max(Math.abs(x1 - x0), Math.abs(y1 - y0), 1);
    for (let i = 0; i <= n; i++) this.set(x0 + ((x1 - x0) * i) / n, y0 + ((y1 - y0) * i) / n, c);
  }
  box(x: number, y: number, w: number, h: number, c: number) { for (let yy = y; yy < y + h; yy++) for (let xx = x; xx < x + w; xx++) this.set(xx, yy, c); }
  /** Draws a one pixel outline in slot 1 around every filled pixel. */
  outline() {
    const add: [number, number][] = [];
    for (let y = 0; y < this.h; y++) for (let x = 0; x < this.w; x++) {
      if (this.g[y][x]) continue;
      if (this.get(x + 1, y) > 1 || this.get(x - 1, y) > 1 || this.get(x, y + 1) > 1 || this.get(x, y - 1) > 1) add.push([x, y]);
    }
    for (const [x, y] of add) this.g[y][x] = 1;
  }
  rows(): string[] { return this.g.map((r) => r.map((c) => (c ? String(c) : '.')).join('')); }
}

function grind(n: number, t: number): string[] {
  const c = new Canvas(n, n);
  const k = n / 32;
  c.disc(16 * k, 13 * k, 11 * k, 2);
  for (let a = 0; a < 8; a++) {
    const ang = (a / 8) * Math.PI * 2 + t * 0.4;
    c.line(16 * k + Math.cos(ang) * 4 * k, 13 * k + Math.sin(ang) * 4 * k, 16 * k + Math.cos(ang) * 10 * k, 13 * k + Math.sin(ang) * 10 * k, 3);
  }
  c.disc(16 * k, 13 * k, 3 * k, 0);
  c.ring(16 * k, 13 * k, 4 * k, 1, 3);
  c.line(5 * k, 15 * k, 1 * k, (20 + t) * k, 2);
  c.line(27 * k, 15 * k, 31 * k, (20 - t) * k, 2);
  c.line(12 * k, 24 * k, (9 + t) * k, 31 * k, 2);
  c.line(20 * k, 24 * k, (23 - t) * k, 31 * k, 2);
  c.outline();
  return c.rows();
}

function gate(n: number, eye: boolean): string[] {
  const c = new Canvas(n, n);
  const k = n / 32;
  const bars = 6;
  for (let i = 0; i < bars; i++) {
    const x = Math.round((3 + i * 5.2) * k);
    c.line(x, 3 * k, x, 29 * k, 2);
    c.set(x, 2 * k, 3);
    c.set(x, 1 * k, 3);
  }
  for (const y of [5, 16, 27]) c.line(1 * k, y * k, 30 * k, y * k, 2);
  for (let i = 0; i < bars - 1; i++) {
    const x = (5.5 + i * 5.2) * k;
    c.ring(x, 10.5 * k, 2 * k, 1, 3);
    c.ring(x, 21.5 * k, 2 * k, 1, 3);
  }
  if (eye) { c.disc(16 * k, 16 * k, 4 * k, 2); c.disc(16 * k, 16 * k, 2 * k, 3); c.set(16 * k, 16 * k, 0); }
  c.outline();
  return c.rows();
}

function dish(n: number, t: number): string[] {
  const c = new Canvas(n, n);
  const k = n / 32;
  for (let x = 0; x < n; x++) {
    const u = (x - 15.5 * k) / (15.5 * k);
    const top = Math.round((1 + u * u * 9) * k);
    for (let y = top; y < top + 3 * k; y++) c.set(x, y, 2);
  }
  c.disc(16 * k, 9 * k, 3 * k, 3);
  c.disc(16 * k, 9 * k, 1 * k, 0);
  c.line(16 * k, 12 * k, 16 * k, 26 * k, 2);
  c.line(15 * k, 12 * k, 15 * k, 26 * k, 2);
  c.box(10 * k, 26 * k, 12 * k, 3 * k, 2);
  c.box(7 * k, 29 * k, 18 * k, 2 * k, 2);
  if (t) { c.set(3 * k, 2 * k, 3); c.set(28 * k, 2 * k, 3); }
  c.outline();
  return c.rows();
}

function arm(n: number, t: number): string[] {
  const c = new Canvas(n, n);
  const k = n / 32;
  const j: [number, number][] = [[2, 1], [9, 7], [15, 12 + t], [20 + t, 19], [22 + t, 27]];
  for (let i = 0; i < j.length - 1; i++) {
    const [x0, y0] = j[i], [x1, y1] = j[i + 1];
    c.line(x0 * k, y0 * k, x1 * k, y1 * k, 2);
    c.line(x0 * k + 1, y0 * k, x1 * k + 1, y1 * k, 2);
  }
  for (const [x, y] of j.slice(0, -1)) c.disc(x * k, y * k, 2 * k, 2);
  for (const [x, y] of j.slice(0, -1)) c.set(x * k, y * k, 3);
  const [nx, ny] = j[j.length - 1];
  c.line(nx * k, ny * k, nx * k, (ny + 4) * k, 3);
  c.line(nx * k + 1, ny * k, nx * k, (ny + 4) * k, 3);
  c.outline();
  return c.rows();
}

function ringOfThem(n: number, t: number): string[] {
  const c = new Canvas(n, n);
  const k = n / 32;
  c.ring(16 * k, 16 * k, 12 * k, 1, 2);
  const people = 9;
  for (let i = 0; i < people; i++) {
    const a = (i / people) * Math.PI * 2 + t * 0.35;
    const x = 16 * k + Math.cos(a) * 12 * k, y = 16 * k + Math.sin(a) * 12 * k;
    c.disc(x, y - 2 * k, 1.2 * k, 2);
    c.line(x, y - 1 * k, x, y + 2 * k, 2);
  }
  c.ring(16 * k, 16 * k, 5 * k, 1, 3);
  c.disc(16 * k, 16 * k, 2 * k, 2);
  return c.rows();
}

function erratum(n: number, t: number): string[] {
  const c = new Canvas(n, n);
  const k = n / 32;
  c.ring(15 * k, 15 * k, 11 * k, 3 * k, 2);
  c.box(4 * k, 14 * k, 23 * k, 3 * k, 2);
  c.box(20 * k, 17 * k, 8 * k, 6 * k, 0);
  for (let i = 0; i < 9; i++) {
    const x = (i * 7 + t * 5) % 30, y = (i * 11 + t * 3) % 30;
    c.box(x * k, y * k, 2, 1, 3);
  }
  c.line(26 * k, 26 * k, 30 * k, 31 * k, 3);
  c.outline();
  return c.rows();
}

