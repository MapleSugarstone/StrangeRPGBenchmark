function every(n: number, t: number): string[] {
  const c = new Canvas(n, n);
  const pts: [number, number][] = [[8, 3], [4, 6], [12, 6], [8, 8], [5, 11], [11, 11], [8, 13]];
  pts.forEach(([x, y], i) => {
    const j = t && i % 2 ? 1 : 0;
    c.disc(x + j, y, 2, i === 3 ? 3 : 2);
  });
  c.outline();
  return c.rows();
}

function closer(n: number, t: number): string[] {
  const c = new Canvas(n, n);
  const open = t ? 4 : 7;
  c.box(16 - open - 7, 10, 7, 14, 3);
  c.box(16 + open, 10, 7, 14, 3);
  c.box(15, 9, 2, 16, 2);
  for (let i = 0; i < 4; i++) { c.line(16 - open - 6, 13 + i * 3, 16 - open - 2, 13 + i * 3, 2); c.line(16 + open + 2, 13 + i * 3, 16 + open + 6, 13 + i * 3, 2); }
  c.box(3, 6, 5, 9, 2); c.box(24, 6, 5, 9, 2);
  c.box(2, 4, 2, 4, 2); c.box(28, 4, 2, 4, 2);
  c.outline();
  return c.rows();
}

function corrector(n: number, t: number): string[] {
  const c = new Canvas(n, n);
  for (let y = 1; y < 31; y++) {
    const x = 13 + Math.round(Math.sin(y * 0.35 + t * 1.5) * 4);
    c.box(x, y, 7, 1, 2);
  }
  for (let i = 0; i < 6; i++) {
    const y = 4 + i * 4;
    const x = 13 + Math.round(Math.sin(y * 0.35 + t * 1.5) * 4);
    c.line(x - 1, y, x + 7, y + 1, 3);
  }
  c.outline();
  return c.rows();
}

function over(n: number, t: number): string[] {
  const c = new Canvas(n, n);
  const glyphs = [[3, 10, 5, 12], [10, 10, 5, 12], [17, 10, 5, 12], [24, 10, 5, 12]];
  for (const [x, y, w, h] of glyphs) {
    c.box(x, y, w, 2, 2); c.box(x, y + h - 2, w, 2, 2); c.box(x, y, 2, h, 2); c.box(x + w - 2, y + 4, 2, h - 4, 2);
  }
  const yy = 16 + (t ? 1 : 0);
  c.box(1, yy, 30, 2, 3);
  c.line(1, yy + 3, 30, yy - 5, 3);
  c.outline();
  return c.rows();
}

function glossBoss(n: number, t: number): string[] {
  const c = new Canvas(n, n);
  c.disc(10, 8, 7, 3);
  c.box(10, 1, 13, 3, 2);
  c.box(16, 1, 3, 29, 2);
  c.box(21, 1, 3, 29, 2);
  c.box(14, 29, 5, 2, 2); c.box(20, 29, 5, 2, 2);
  if (t) { c.set(26, 6, 3); c.set(27, 8, 3); c.set(26, 10, 3); }
  else { c.set(27, 5, 3); c.set(26, 9, 3); c.set(28, 11, 3); }
  c.outline();
  return c.rows();
}

