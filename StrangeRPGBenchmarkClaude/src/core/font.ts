export interface Glyph { w: number; rows: string[] }
export const GLYPHS = new Map<string, Glyph>();
for (const [ch, src] of Object.entries(SRC)) {
  const rows = src.split('/');
  GLYPHS.set(ch, { w: Math.max(...rows.map(r => r.length)), rows });
}
GLYPHS.set(' ', { w: 2, rows: [] });

export const LINE_H = 7;

export function charW(ch: string): number {
  const g = GLYPHS.get(ch) ?? GLYPHS.get('?')!;
  return g.w + 1;
}

export function textW(s: string): number {
  let w = 0;
  for (let i = 0; i < s.length; i++) {
    if (s[i] === '^') { i++; continue; }
    w += charW(s[i]);
  }
  return Math.max(0, w - 1);
}

/** Wraps text to lines no wider than `maxW`, carrying color codes across line breaks. */
export function wrap(text: string, maxW: number): string[] {
  const out: string[] = [];
  for (const para of text.split('\n')) {
    const words = para.split(' ');
    let line = '';
    let color = '';
    let lineColor = '';
    for (const word of words) {
      const trial = line ? line + ' ' + word : word;
      if (textW(trial) > maxW && line) {
        out.push(lineColor + line);
        lineColor = color;
        line = word;
      } else {
        line = trial;
      }
      for (let i = 0; i < word.length; i++) if (word[i] === '^') { color = word[i + 1] === '0' ? '' : '^' + word[i + 1]; i++; }
    }
    out.push(lineColor + line);
  }
  return out;
}
