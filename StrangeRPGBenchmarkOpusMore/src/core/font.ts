export interface Glyph { w: number; rows: number[]; }

const glyphs = new Map<string, Glyph>();
for (const [ch, def] of Object.entries(G)) {
  const rows = def.split('/');
  const w = Math.max(...rows.map((r) => r.length));
  const bits = rows.map((r) => {
    let b = 0;
    for (let i = 0; i < r.length; i++) if (r[i] === '#') b |= 1 << i;
    return b;
  });
  glyphs.set(ch, { w, rows: bits });
}

export const SPACE_W = 3;
export const LINE_H = 10;

export function glyph(ch: string): Glyph | undefined {
  return glyphs.get(ch) ?? glyphs.get(ch.toUpperCase());
}

export function charWidth(ch: string): number {
  if (ch === ' ') return SPACE_W;
  const g = glyph(ch);
  return g ? g.w : 3;
}

export function textWidth(s: string): number {
  let w = 0;
  for (let i = 0; i < s.length; i++) w += charWidth(s[i]) + 1;
  return Math.max(0, w - 1);
}

// Word-wraps text to a pixel width. '\n' forces a break.
export function wrap(text: string, maxW: number): string[] {
  const out: string[] = [];
  for (const para of text.split('\n')) {
    const words = para.split(' ');
    let line = '';
    for (const word of words) {
      const trial = line ? line + ' ' + word : word;
      if (textWidth(trial) <= maxW || !line) {
        line = trial;
      } else {
        out.push(line);
        line = word;
      }
    }
    out.push(line);
  }
  return out;
}
